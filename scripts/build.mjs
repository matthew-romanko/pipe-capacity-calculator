/** Build one classic script so index.html also works when opened over file://.
 * Keep the readable ES modules in src/ for Node tests and future maintenance.
 */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
let lookup=read('src/lookup-data.js');
let calculations=read('src/calculations.js');
let app=read('src/app.js');
if(!lookup.startsWith('// Generated') || !lookup.includes('export default {')) throw Error('Unexpected lookup module format');
if(!calculations.includes("import lookup from './lookup-data.js';")) throw Error('Unexpected calculations module import');
if(!app.includes("import {calculateWorksheet, materials, pipeSizesInches} from './calculations.js';")) throw Error('Unexpected app module import');
lookup=lookup.replace('export default {','const lookup = {');
calculations=calculations.replace("import lookup from './lookup-data.js';",'').replace(/^export /gm,'');
app=app.replace("import {calculateWorksheet, materials, pipeSizesInches} from './calculations.js';",'');
const result=`/* Generated from src/ — use npm run build to regenerate. Do not edit this file. */\n(()=>{\n'use strict';\n${lookup}\n${calculations}\n${app}\n})();\n`;
mkdirSync(resolve(root,'dist'),{recursive:true});
const publicFiles = [
  ['index.html','docs/index.html'],
  ['css/styles.css','docs/css/styles.css'],
  ['dist/app.js','docs/dist/app.js'],
];
if(process.argv.includes('--check')) {
  if(read('dist/app.js')!==result) throw Error('dist/app.js is out of date: run npm run build');
  for(const [source,target] of publicFiles) {
    if(read(target)!==(source==='dist/app.js'?result:read(source))) {
      throw Error(`${target} differs from ${source}; run npm run build`);
    }
  }
  console.log('Browser bundle and GitHub Pages /docs files match source.');
} else {
  writeFileSync(resolve(root,'dist/app.js'),result);
  for(const [source,target] of publicFiles) {
    mkdirSync(resolve(root,target,'..'),{recursive:true});
    writeFileSync(resolve(root,target),source==='dist/app.js'?result:read(source));
  }
  console.log('Wrote dist/app.js and synchronized docs/ for GitHub Pages.');
}

